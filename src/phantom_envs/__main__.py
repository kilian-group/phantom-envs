"""Command line: generate a PhantomEnvs environment.

Needs SWI-Prolog (``swipl``) on PATH. The paper's datasets are regenerated by
reproduce_paper/scripts/generate_paper_data.py.

Usage:
    # A new environment from a preset (pw, pwcons, pwcomp), with EnvConfig fields overridden as key=value
    uv run phantom_envs generate --preset pwcons --output_dir data/envs/pwcons-seed2 seed=2
    uv run phantom_envs generate --output_dir /tmp/pw 'kinds=[base,count]' split.cap_factor=1
"""

import argparse
import json
import logging
from dataclasses import asdict

from omegaconf import OmegaConf

from phantom_envs._types import EnvConfig, SplitConfig
from phantom_envs.environment import PRESETS, PhantomEnv, generate


def tuples(d: dict) -> dict:
    """Turn lists back into tuples, for config fields that went through OmegaConf.

    Args:
        d: A config as a dict.

    Returns:
        The dict with list values as tuples.
    """
    return {k: tuple(v) if isinstance(v, list) else v for k, v in d.items()}


def config_from_cli(preset: str, overrides: list[str]) -> EnvConfig:
    """Build a config from a preset and ``key=value`` overrides.

    Args:
        preset: Name of a preset in :data:`PRESETS`.
        overrides: Dot-notation overrides, e.g. ``seed=2`` or ``split.cap_factor=1``.

    Returns:
        The config.
    """
    merged = OmegaConf.to_container(OmegaConf.merge(asdict(PRESETS[preset]), OmegaConf.from_cli(overrides)))
    split = SplitConfig(**tuples(merged.pop("split")))
    return EnvConfig(**tuples(merged), split=split)


def main(args: argparse.Namespace) -> None:
    """Run the chosen command and print the environment's summary."""
    env: PhantomEnv
    match args.command:
        case "generate":
            config = config_from_cli(args.preset, args.overrides)
            env = generate(args.output_dir, config, workers=args.workers, overwrite=args.overwrite)
    summary = {k: env.manifest[k] for k in ("content_hash", "num_people", "num_tasks")}
    print(json.dumps({"path": str(env.path)} | summary, indent=2))


def cli() -> None:
    """Entry point of the ``phantom_envs`` command."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
    parser = argparse.ArgumentParser(prog="phantom_envs", description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)

    gen = commands.add_parser("generate", help="Generate a new environment.")
    gen.add_argument("--preset", default="pw", choices=list(PRESETS), help="Starting config (default: pw).")
    gen.add_argument("--output_dir", required=True, help="Where to write the environment.")
    gen.add_argument("--workers", type=int, default=8, help="Processes for Prolog queries (default: 8).")
    gen.add_argument("--overwrite", action="store_true", help="Replace an existing environment.")

    args, overrides = parser.parse_known_args()
    args.overrides = overrides
    main(args)


if __name__ == "__main__":
    cli()
